-- PROJETO SMARTCOFFEE

CREATE DATABASE SMARTCOFFEE_GABRIELA;

USE SMARTCOFFEE_GABRIELA;

CREATE TABLE PEDIDOS (
ID_PEDIDOS INT AUTO_INCREMENT PRIMARY KEY,
DATA_HORA DATETIME (60) NOT NULL,
STATUS VARCHAR (60),
TIPO_PEDIDO ENUM ('DELIVERY', 'PRESENCIAL'),
VALOR_TOTAL VARCHAR (100) NOT NULL
);

CREATE TABLE PRODUTO (
ID_PRODUTO INT AUTO_INCREMENT PRIMARY KEY,
NOME VARCHAR (60) NOT NULL, 
DESCRICAO VARCHAR (60), 
PRECO_UNITARIO DECIMAL,
CATEGORIA VARCHAR (60)
);

CREATE TABLE PAGAMENTOS (
ID_PAGAMENTOS INT AUTO_INCREMENT PRIMARY KEY,
VALOR_PAGO VARCHAR (60) NOT NULL,
STATUS_PAGAMENTOS VARCHAR (60) NOT NULL,
DATA_HORA_SAIDA ENUM ('DATA', 'HORA', 'SAIDA'),
FORMA_DE_PAGAMENTO ENUM ('PIX', 'CARTAO DEBITO')
);

CREATE TABLE ESTOQUE (
ID_ESTOQUE INT AUTO_INCREMENT PRIMARY KEY,
NOME_INSUMO VARCHAR (60) NOT NULL,
QUANTIDADE_ATUAL DATE,
UNIDADE_MEDIDA ENUM ('KG', 'ML', 'UN'),
QUANTIDADE_MINIMA VARCHAR (60)
);

CREATE TABLE DELIVERY (
ID_DELIVERY INT AUTO_INCREMENT PRIMARY KEY,
ENDERECO_ENTREGA VARCHAR (60),
TAXA_ENTREGA VARCHAR (60),
STATUS_ENTREGA VARCHAR (60),
DATA_HORA_SAIDA ENUM ('DATA', 'HORA', 'SAIDA')
);

CREATE TABLE CLIENTE (
ID_CLIENETE INT AUTO_INCREMENT PRIMARY KEY,
NOME VARCHAR (60) NOT NULL,
CPF VARCHAR (14) NOT NULL,
EMAIL VARCHAR (40) NOT NULL,
TELEFONE VARCHAR (11) NOT NULL, 
DATA_ENDERECO VARCHAR (60) NOT NULL
);

CREATE TABLE FIDELIDADE (
ID_FIDELIDADE INT AUTO_INCREMENT PRIMARY KEY,
SALDO_PONTOS VARCHAR (60) NOT NULL,
DATA_ULTIMA_ATUALIZACAO DATE
);

CREATE TABLE FUNCIONARIOS (
ID_FUNCIONARIOS INT AUTO_INCREMENT PRIMARY KEY,
NOME VARCHAR (60) NOT NULL,
SALARIO VARCHAR (60) NOT NULL, 
CPF VARCHAR (14) NOT NULL,
DATA_ADMISSAO DATETIME
);

